/* Contact page: adds a reference for the page the visitor came from to the sales
   email subject, e.g. "(Ref C26)". Codes come from js/page-refs.js (generated by
   "5. Website Redesign/tools/sync-page-refs.py"); Thai pages add "T" (C26T).
   A page with no code yet falls back to its address: "(from /new/page)".
   Reads document.referrer only. Stores nothing, sets no cookies.
   Used by Pages/Contact/Index.cshtml and Pages/ThaiPages/Contact.cshtml. */
(function () {
  var REFS = window.HANA_PAGE_REFS || { routes: {}, files: {} };
  var tag = "";
  try {
    var ref = new URL(document.referrer);
    if (ref.hostname === location.hostname) {
      var path = ref.pathname;
      var site = path.match(/^(\/Hana-Site-[^\/]+\/)(.*)$/);   // preview and staging sites
      if (site || /\.html$/.test(path)) {
        var file = site ? site[2] : path.replace(/^\//, "");
        if (file === "" || /\/$/.test(file)) file += "index.html";
        var thf = file.indexOf("th/") === 0;
        if (thf) file = file.slice(3);
        if (!/(^|-)contact\.html$/.test(file)) {
          tag = REFS.files[file] ? "Ref " + REFS.files[file] + (thf ? "T" : "") : "from " + path;
        }
      } else {
        path = path.replace(/\/+$/, "") || "/";
        var th = path === "/th" || path.indexOf("/th/") === 0;
        var route = th ? (path.slice(3) || "/") : path;
        if (!/^\/contact(\/|$)/i.test(route)) {
          tag = REFS.routes[route] ? "Ref " + REFS.routes[route] + (th ? "T" : "") : "from " + path;
        }
      }
    }
  } catch (e) { /* no previous page: typed address, bookmark, search engine, email link */ }
  if (!tag) return;

  document.querySelectorAll('a[href^="mailto:info-request@hanaus.com"]').forEach(function (link) {
    var parts = link.getAttribute("href").split("?subject=");
    var subject = decodeURIComponent(parts[1] || "");
    if (subject.indexOf("(Ref ") !== -1 || subject.indexOf("(from ") !== -1) return;
    link.setAttribute("href", parts[0] + "?subject=" + encodeURIComponent(subject + " (" + tag + ")"));
  });
})();
